CREATE TABLE boleta (
    id BIGINT NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    fecha DATETIME(6) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(100) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    direccion VARCHAR(500) NOT NULL,
    region VARCHAR(100) NOT NULL,
    comuna VARCHAR(100) NOT NULL,
    indicaciones VARCHAR(300) NULL,
    metodo_pago VARCHAR(20) NOT NULL,
    pago_simulado BIT(1) NOT NULL DEFAULT b'1',
    descuento_usuario DECIMAL(5,2) NOT NULL,
    subtotal DECIMAL(16,2) NOT NULL,
    ahorro DECIMAL(16,2) NOT NULL,
    total DECIMAL(16,2) NOT NULL,
    stock_descontado BIT(1) NOT NULL DEFAULT b'0',
    stock_restituido BIT(1) NOT NULL DEFAULT b'0',
    fecha_cancelacion DATETIME(6) NULL,
    PRIMARY KEY (id),
    INDEX ix_boleta_usuario_fecha (usuario_id, fecha, id),
    INDEX ix_boleta_estado_fecha (estado, fecha, id),
    CONSTRAINT fk_boleta_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_boleta_estado CHECK (BINARY estado IN ('PENDIENTE','PROCESANDO','ENVIADO','COMPLETADO','CANCELADO')),
    CONSTRAINT ck_boleta_metodo CHECK (BINARY metodo_pago IN ('webpay','transferencia')),
    CONSTRAINT ck_boleta_pago_simulado CHECK (pago_simulado = b'1'),
    CONSTRAINT ck_boleta_version CHECK (version >= 0),
    CONSTRAINT ck_boleta_descuento CHECK (descuento_usuario BETWEEN 0 AND 100),
    -- Ahorro puede ser negativo por redondeo al peso de precios base con centavos.
    CONSTRAINT ck_boleta_importes CHECK (subtotal >= 0 AND total >= 0 AND total = subtotal - ahorro),
    CONSTRAINT ck_boleta_restitucion CHECK (stock_restituido = b'0' OR (stock_descontado = b'1' AND BINARY estado = 'CANCELADO'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
